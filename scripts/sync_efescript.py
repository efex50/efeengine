#!/usr/bin/env python3
"""Mirror efescript and the crates it needs into the standalone efescript repo (stdlib only).

efeengine is the source of truth; the efescript repo is a read-only mirror. Never edit the
mirror by hand: the next sync overwrites it.

Usage:
  scripts/sync_efescript.py [--dest DIR] [--no-check] [--commit] [--push]

  --dest DIR   mirror checkout (default: ../efescript next to this repo)
  --no-check   skip `cargo build` in the mirror
  --commit     commit the mirror with a message naming the efeengine commit
  --push       push the mirror's current branch (implies --commit)

The mirror is a Cargo workspace with the crates below under crates/. Its root
Cargo.toml, .gitignore and README.md are generated here; LICENSE is copied from this repo.
"""
import argparse
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Crates copied to <dest>/crates/<name>. efescript and everything it depends on by path.
CRATES = ["efescript", "efevm", "efevm-jit", "efa", "efemod", "calc"]
# Workspace members of the mirror (paths relative to its root).
MEMBERS = [
    "crates/efescript",
    "crates/efescript/proc_macros",
    "crates/efescript/strtohx",
    "crates/calc",
    "crates/efevm",
    "crates/efevm-jit",
    "crates/efa",
    "crates/efemod",
]
EXCLUDE = ["crates/efa/fuzz"]
# Directory names never copied.
SKIP_DIRS = {"target", ".git", "__pycache__"}
# Top-level entries of the mirror the sync owns; anything else in the mirror is removed.
OWNED = {"crates", "Cargo.toml", "Cargo.lock", ".gitignore", "README.md", "LICENSE"}

WORKSPACE = """# Generated by efeengine/scripts/sync_efescript.py. Do not edit: this repository is a
# mirror of https://github.com/efex50/efeengine (crates/efescript and its dependencies).
[workspace]
resolver = "3"
members = [
{members}
]
exclude = [{exclude}]

[profile.optimize]
inherits = "release"
opt-level = 3
strip = true
lto = "fat"
panic = "abort"
"""

MIRROR_NOTE = """> **Mirror.** This repository is generated from
> [efeengine](https://github.com/efex50/efeengine) (`crates/efescript`, `efevm`, `efevm-jit`,
> `efa`, `efemod`, `calc`) by `scripts/sync_efescript.py`. Send changes there; edits here are
> overwritten by the next sync.

"""


def log(msg):
    print(f"==> {msg}", flush=True)


def run(cmd, cwd, capture=False):
    r = subprocess.run(cmd, cwd=cwd, text=True, capture_output=capture)
    if r.returncode != 0:
        if capture:
            sys.stderr.write(r.stdout + r.stderr)
        sys.exit(f"command failed ({r.returncode}): {' '.join(cmd)}")
    return r.stdout.strip() if capture else ""


def ignore(_dir, names):
    return [n for n in names if n in SKIP_DIRS]


def sync(dest: Path):
    if not (dest / ".git").exists():
        sys.exit(f"{dest} is not a git checkout; clone the efescript repo there first")
    for entry in dest.iterdir():
        if entry.name == ".git" or entry.name == "target":
            continue
        if entry.name not in OWNED or entry.name == "crates":
            log(f"remove {entry.name}")
            shutil.rmtree(entry) if entry.is_dir() else entry.unlink()
    for name in CRATES:
        src = ROOT / "crates" / name
        log(f"copy crates/{name}")
        shutil.copytree(src, dest / "crates" / name, ignore=ignore)
    members = "\n".join(f'    "{m}",' for m in MEMBERS)
    exclude = ", ".join(f'"{e}"' for e in EXCLUDE)
    (dest / "Cargo.toml").write_text(WORKSPACE.format(members=members, exclude=exclude))
    (dest / ".gitignore").write_text("target/\n")
    readme = (ROOT / "crates/efescript/README.md").read_text()
    (dest / "README.md").write_text(MIRROR_NOTE + readme)
    shutil.copy2(ROOT / "LICENSE", dest / "LICENSE")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dest", type=Path, default=ROOT.parent / "efescript")
    ap.add_argument("--no-check", action="store_true")
    ap.add_argument("--commit", action="store_true")
    ap.add_argument("--push", action="store_true")
    a = ap.parse_args()
    dest = a.dest.resolve()

    sha = run(["git", "rev-parse", "--short", "HEAD"], ROOT, capture=True)
    dirty = run(["git", "status", "--porcelain", "--", *[f"crates/{c}" for c in CRATES]], ROOT, capture=True)
    if dirty and (a.commit or a.push):
        sys.exit("uncommitted changes in the mirrored crates; commit them in efeengine first:\n" + dirty)

    sync(dest)
    if not a.no_check:
        log("cargo build (mirror)")
        run(["cargo", "build", "--quiet"], dest)

    if a.commit or a.push:
        run(["git", "add", "-A"], dest)
        if not run(["git", "status", "--porcelain"], dest, capture=True):
            log("mirror already up to date")
        else:
            # The mirror commits as the efeengine author.
            name = run(["git", "config", "user.name"], ROOT, capture=True)
            email = run(["git", "config", "user.email"], ROOT, capture=True)
            subject = run(["git", "log", "-1", "--format=%s"], ROOT, capture=True)
            msg = f"Sync from efeengine {sha}\n\nefeengine {sha}: {subject}\n"
            run(["git", "-c", f"user.name={name}", "-c", f"user.email={email}", "commit", "-q", "-m", msg], dest)
            log(f"committed mirror at efeengine {sha}")
        if a.push:
            branch = run(["git", "rev-parse", "--abbrev-ref", "HEAD"], dest, capture=True)
            log(f"push {branch}")
            run(["git", "push", "origin", branch], dest)
    log("done")


if __name__ == "__main__":
    main()
